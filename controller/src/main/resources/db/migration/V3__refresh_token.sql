CALL LIB_begin_migration('3');

-- Refresh tokens rotate on every use. All tokens of one login share ID_FAMILY_KEY; presenting an already
-- used token deactivates the whole family. Rows past DTT_EXPIRES are physically deleted by a job.
CREATE TABLE T_REFRESH_TOKEN (
    ID_REFRESH_TOKEN_KEY  UUID         NOT NULL,
    ID_REFRESH_TOKEN_VER  BIGINT       NOT NULL,
    IS_ACTIVE             BOOLEAN      NOT NULL DEFAULT TRUE,
    DTT_MOD               TIMESTAMPTZ  NOT NULL,
    ID_USR_MOD            UUID         NOT NULL,
    ID_EVT_KEY            UUID         NOT NULL,
    DTT_CREATED           TIMESTAMPTZ  NOT NULL,
    ID_USR_CREATED        UUID         NOT NULL,
    ID_ACCOUNT_KEY        UUID         NOT NULL,
    ID_USR_KEY            UUID         NOT NULL,
    ID_FAMILY_KEY         UUID         NOT NULL,
    TX_TOKEN_HASH         VARCHAR(64)  NOT NULL,
    DTT_EXPIRES           TIMESTAMPTZ  NOT NULL,
    DTT_USED              TIMESTAMPTZ,
    CONSTRAINT PK_REFRESH_TOKEN PRIMARY KEY (ID_REFRESH_TOKEN_KEY),
    CONSTRAINT FK_REFRESH_TOKEN_ACCOUNT FOREIGN KEY (ID_ACCOUNT_KEY) REFERENCES T_ACCOUNT (ID_ACCOUNT_KEY),
    CONSTRAINT FK_REFRESH_TOKEN_USER FOREIGN KEY (ID_USR_KEY) REFERENCES T_USER (ID_USR_KEY)
);
CALL LIB_attach_header('t_refresh_token');
CREATE UNIQUE INDEX UK_REFRESH_TOKEN_HASH ON T_REFRESH_TOKEN (TX_TOKEN_HASH);
CREATE INDEX IDX_REFRESH_TOKEN_FAMILY ON T_REFRESH_TOKEN (ID_FAMILY_KEY);
CREATE INDEX IDX_REFRESH_TOKEN_EXPIRES ON T_REFRESH_TOKEN (DTT_EXPIRES);
