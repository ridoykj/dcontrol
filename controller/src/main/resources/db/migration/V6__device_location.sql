-- Last location fix per device (find my phone). One active row per device, replaced on every refresh.
-- Not audited, and physically deleted when the user clears it or unpairs the device: a hidden copy of a
-- location the user deleted would be misleading.
CREATE TABLE T_DEVICE_LOCATION (
    ID_DEVICE_LOCATION_KEY  UUID          NOT NULL,
    ID_DEVICE_LOCATION_VER  BIGINT        NOT NULL,
    IS_ACTIVE               BOOLEAN       NOT NULL DEFAULT TRUE,
    DTT_MOD                 TIMESTAMPTZ   NOT NULL,
    ID_USR_MOD              UUID          NOT NULL,
    ID_EVT_KEY              UUID          NOT NULL,
    DTT_CREATED             TIMESTAMPTZ   NOT NULL,
    ID_USR_CREATED          UUID          NOT NULL,
    ID_ACCOUNT_KEY          UUID          NOT NULL,
    ID_DEVICE_KEY           UUID          NOT NULL,
    DEC_LATITUDE            NUMERIC(9,6)  NOT NULL,
    DEC_LONGITUDE           NUMERIC(9,6)  NOT NULL,
    DEC_ACCURACY_M          NUMERIC(9,1)  NOT NULL,
    DEC_ALTITUDE_M          NUMERIC(8,1),
    DTT_FIXED               TIMESTAMPTZ   NOT NULL,
    TX_PROVIDER             VARCHAR(16)   NOT NULL,
    IS_STALE                BOOLEAN       NOT NULL,
    CONSTRAINT PK_DEVICE_LOCATION PRIMARY KEY (ID_DEVICE_LOCATION_KEY),
    CONSTRAINT FK_DEVICE_LOCATION_ACCOUNT FOREIGN KEY (ID_ACCOUNT_KEY) REFERENCES T_ACCOUNT (ID_ACCOUNT_KEY),
    CONSTRAINT FK_DEVICE_LOCATION_DEVICE FOREIGN KEY (ID_DEVICE_KEY) REFERENCES T_DEVICE (ID_DEVICE_KEY),
    CONSTRAINT CK_DEVICE_LOCATION_LATITUDE CHECK (DEC_LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_DEVICE_LOCATION_LONGITUDE CHECK (DEC_LONGITUDE BETWEEN -180 AND 180),
    CONSTRAINT CK_DEVICE_LOCATION_ACCURACY CHECK (DEC_ACCURACY_M BETWEEN 0 AND 1000000),
    CONSTRAINT CK_DEVICE_LOCATION_ALTITUDE CHECK (DEC_ALTITUDE_M BETWEEN -100000 AND 100000),
    CONSTRAINT CK_DEVICE_LOCATION_PROVIDER CHECK (TX_PROVIDER IN ('GPS', 'NETWORK', 'FUSED', 'PASSIVE', 'OTHER'))
);
CALL LIB_attach_header('t_device_location');
CREATE UNIQUE INDEX UK_DEVICE_LOCATION_DEVICE ON T_DEVICE_LOCATION (ID_DEVICE_KEY) WHERE IS_ACTIVE;
