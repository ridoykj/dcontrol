-- One file moving between a browser and a phone through the controller's disk spool
-- (docs/protocol/transfers-v1.md). Operational data: not audited. Rows in a final state are
-- physically deleted by TransferCleanupJob after the row retention period.
CREATE TABLE T_FILE_TRANSFER (
    ID_FILE_TRANSFER_KEY  UUID           NOT NULL,
    ID_FILE_TRANSFER_VER  BIGINT         NOT NULL,
    IS_ACTIVE             BOOLEAN        NOT NULL DEFAULT TRUE,
    DTT_MOD               TIMESTAMPTZ    NOT NULL,
    ID_USR_MOD            UUID           NOT NULL,
    ID_EVT_KEY            UUID           NOT NULL,
    ID_STATE_KEY          UUID           NOT NULL,
    ID_ACTION_KEY         UUID           NOT NULL,
    DTT_CREATED           TIMESTAMPTZ    NOT NULL,
    ID_USR_CREATED        UUID           NOT NULL,
    ID_ACCOUNT_KEY        UUID           NOT NULL,
    ID_DEVICE_KEY         UUID           NOT NULL,
    TX_DIRECTION          VARCHAR(16)    NOT NULL,
    TX_DEVICE_PATH        VARCHAR(4096)  NOT NULL,
    TX_FILE_NAME          VARCHAR(255)   NOT NULL,
    -- Unknown until the phone reports it for FROM_DEVICE transfers.
    CT_SIZE_BYTES         BIGINT,
    CT_RECEIVED_BYTES     BIGINT         NOT NULL,
    TX_SHA256             VARCHAR(64),
    TX_ERROR_CODE         VARCHAR(32),
    DTT_EXPIRES           TIMESTAMPTZ    NOT NULL,
    DTT_FINISHED          TIMESTAMPTZ,
    CONSTRAINT PK_FILE_TRANSFER PRIMARY KEY (ID_FILE_TRANSFER_KEY),
    CONSTRAINT FK_FILE_TRANSFER_ACCOUNT FOREIGN KEY (ID_ACCOUNT_KEY) REFERENCES T_ACCOUNT (ID_ACCOUNT_KEY),
    CONSTRAINT FK_FILE_TRANSFER_DEVICE FOREIGN KEY (ID_DEVICE_KEY) REFERENCES T_DEVICE (ID_DEVICE_KEY),
    CONSTRAINT CK_FILE_TRANSFER_DIRECTION CHECK (TX_DIRECTION IN ('TO_DEVICE', 'FROM_DEVICE')),
    CONSTRAINT CK_FILE_TRANSFER_SIZE CHECK (CT_SIZE_BYTES >= 0),
    CONSTRAINT CK_FILE_TRANSFER_RECEIVED CHECK (CT_RECEIVED_BYTES >= 0 AND CT_RECEIVED_BYTES <= COALESCE(CT_SIZE_BYTES, CT_RECEIVED_BYTES)),
    CONSTRAINT CK_FILE_TRANSFER_SHA256 CHECK (TX_SHA256 ~ '^[0-9a-f]{64}$')
);
CALL LIB_attach_header('t_file_transfer');
CALL LIB_attach_fsm('t_file_transfer', 'TRANSFER');
CREATE INDEX IDX_FILE_TRANSFER_ACCOUNT ON T_FILE_TRANSFER (ID_ACCOUNT_KEY);
CREATE INDEX IDX_FILE_TRANSFER_DEVICE_STATE ON T_FILE_TRANSFER (ID_DEVICE_KEY, ID_STATE_KEY);
CREATE INDEX IDX_FILE_TRANSFER_EXPIRES ON T_FILE_TRANSFER (DTT_EXPIRES);
