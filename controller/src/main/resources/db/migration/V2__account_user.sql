CREATE TABLE T_ACCOUNT (
    ID_ACCOUNT_KEY   UUID         NOT NULL,
    ID_ACCOUNT_VER   BIGINT       NOT NULL,
    IS_ACTIVE        BOOLEAN      NOT NULL DEFAULT TRUE,
    DTT_MOD          TIMESTAMPTZ  NOT NULL,
    ID_USR_MOD       UUID         NOT NULL,
    ID_EVT_KEY       UUID         NOT NULL,
    DTT_CREATED      TIMESTAMPTZ  NOT NULL,
    ID_USR_CREATED   UUID         NOT NULL,
    TX_NAME          VARCHAR(120) NOT NULL,
    CONSTRAINT PK_ACCOUNT PRIMARY KEY (ID_ACCOUNT_KEY)
);
CALL LIB_attach_header('t_account');
CALL LIB_create_audit('t_account');

CREATE TABLE T_USER (
    ID_USR_KEY          UUID         NOT NULL,
    ID_USR_VER          BIGINT       NOT NULL,
    IS_ACTIVE           BOOLEAN      NOT NULL DEFAULT TRUE,
    DTT_MOD             TIMESTAMPTZ  NOT NULL,
    ID_USR_MOD          UUID         NOT NULL,
    ID_EVT_KEY          UUID         NOT NULL,
    DTT_CREATED         TIMESTAMPTZ  NOT NULL,
    ID_USR_CREATED      UUID         NOT NULL,
    ID_ACCOUNT_KEY      UUID         NOT NULL,
    TX_EMAIL            VARCHAR(254) NOT NULL,
    TX_PASSWORD_HASH    VARCHAR(255) NOT NULL,
    TX_DISPLAY_NAME     VARCHAR(80)  NOT NULL,
    TX_ROLE             VARCHAR(16)  NOT NULL,
    DTT_EMAIL_VERIFIED  TIMESTAMPTZ,
    CONSTRAINT PK_USER PRIMARY KEY (ID_USR_KEY),
    CONSTRAINT FK_USER_ACCOUNT FOREIGN KEY (ID_ACCOUNT_KEY) REFERENCES T_ACCOUNT (ID_ACCOUNT_KEY),
    CONSTRAINT CK_USER_ROLE CHECK (TX_ROLE IN ('OWNER', 'SYSTEM'))
);
CALL LIB_attach_header('t_user');
CALL LIB_create_audit('t_user');
CREATE UNIQUE INDEX UK_USER_EMAIL ON T_USER (lower(TX_EMAIL)) WHERE IS_ACTIVE;
CREATE INDEX IDX_USER_ACCOUNT ON T_USER (ID_ACCOUNT_KEY);

