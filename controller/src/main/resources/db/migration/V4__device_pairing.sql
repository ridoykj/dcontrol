CREATE TABLE T_DEVICE (
    ID_DEVICE_KEY       UUID         NOT NULL,
    ID_DEVICE_VER       BIGINT       NOT NULL,
    IS_ACTIVE           BOOLEAN      NOT NULL DEFAULT TRUE,
    DTT_MOD             TIMESTAMPTZ  NOT NULL,
    ID_USR_MOD          UUID         NOT NULL,
    ID_EVT_KEY          UUID         NOT NULL,
    ID_STATE_KEY        UUID         NOT NULL,
    ID_ACTION_KEY       UUID         NOT NULL,
    DTT_CREATED         TIMESTAMPTZ  NOT NULL,
    ID_USR_CREATED      UUID         NOT NULL,
    ID_ACCOUNT_KEY      UUID         NOT NULL,
    TX_NAME             VARCHAR(64)  NOT NULL,
    TX_MANUFACTURER     VARCHAR(64)  NOT NULL,
    TX_MODEL            VARCHAR(64)  NOT NULL,
    TX_ANDROID_VERSION  VARCHAR(16)  NOT NULL,
    CT_SDK_INT          INTEGER      NOT NULL,
    TX_APP_VERSION      VARCHAR(32)  NOT NULL,
    TX_SECRET_HASH      VARCHAR(64)  NOT NULL,
    DTT_PAIRED          TIMESTAMPTZ  NOT NULL,
    CONSTRAINT PK_DEVICE PRIMARY KEY (ID_DEVICE_KEY),
    CONSTRAINT FK_DEVICE_ACCOUNT FOREIGN KEY (ID_ACCOUNT_KEY) REFERENCES T_ACCOUNT (ID_ACCOUNT_KEY),
    CONSTRAINT CK_DEVICE_SDK_INT CHECK (CT_SDK_INT BETWEEN 26 AND 100)
);
CALL LIB_attach_header('t_device');
CALL LIB_attach_fsm('t_device', 'DEVICE');
CALL LIB_create_audit('t_device');
CREATE INDEX IDX_DEVICE_ACCOUNT ON T_DEVICE (ID_ACCOUNT_KEY);

-- Pairing tokens live for minutes. Rows past DTT_EXPIRES are physically deleted by a job.
CREATE TABLE T_PAIRING_TOKEN (
    ID_PAIRING_TOKEN_KEY  UUID         NOT NULL,
    ID_PAIRING_TOKEN_VER  BIGINT       NOT NULL,
    IS_ACTIVE             BOOLEAN      NOT NULL DEFAULT TRUE,
    DTT_MOD               TIMESTAMPTZ  NOT NULL,
    ID_USR_MOD            UUID         NOT NULL,
    ID_EVT_KEY            UUID         NOT NULL,
    ID_STATE_KEY          UUID         NOT NULL,
    ID_ACTION_KEY         UUID         NOT NULL,
    DTT_CREATED           TIMESTAMPTZ  NOT NULL,
    ID_USR_CREATED        UUID         NOT NULL,
    ID_ACCOUNT_KEY        UUID         NOT NULL,
    ID_DEVICE_KEY         UUID,
    TX_TOKEN_HASH         VARCHAR(64)  NOT NULL,
    DTT_EXPIRES           TIMESTAMPTZ  NOT NULL,
    CONSTRAINT PK_PAIRING_TOKEN PRIMARY KEY (ID_PAIRING_TOKEN_KEY),
    CONSTRAINT FK_PAIRING_TOKEN_ACCOUNT FOREIGN KEY (ID_ACCOUNT_KEY) REFERENCES T_ACCOUNT (ID_ACCOUNT_KEY),
    CONSTRAINT FK_PAIRING_TOKEN_DEVICE FOREIGN KEY (ID_DEVICE_KEY) REFERENCES T_DEVICE (ID_DEVICE_KEY)
);
CALL LIB_attach_header('t_pairing_token');
CALL LIB_attach_fsm('t_pairing_token', 'PAIRING');
CREATE UNIQUE INDEX UK_PAIRING_TOKEN_HASH ON T_PAIRING_TOKEN (TX_TOKEN_HASH);
CREATE INDEX IDX_PAIRING_TOKEN_EXPIRES ON T_PAIRING_TOKEN (DTT_EXPIRES);
CREATE INDEX IDX_PAIRING_TOKEN_ACCOUNT ON T_PAIRING_TOKEN (ID_ACCOUNT_KEY);

-- Last known presence of a device. Written on connect/disconnect and at most every few minutes from
-- heartbeats, so it is kept out of T_DEVICE (and its audit trail).
CREATE TABLE T_DEVICE_STATUS (
    ID_DEVICE_STATUS_KEY  UUID         NOT NULL,
    ID_DEVICE_STATUS_VER  BIGINT       NOT NULL,
    IS_ACTIVE             BOOLEAN      NOT NULL DEFAULT TRUE,
    DTT_MOD               TIMESTAMPTZ  NOT NULL,
    ID_USR_MOD            UUID         NOT NULL,
    ID_EVT_KEY            UUID         NOT NULL,
    DTT_CREATED           TIMESTAMPTZ  NOT NULL,
    ID_USR_CREATED        UUID         NOT NULL,
    ID_ACCOUNT_KEY        UUID         NOT NULL,
    ID_DEVICE_KEY         UUID         NOT NULL,
    DTT_LAST_SEEN         TIMESTAMPTZ  NOT NULL,
    CT_BATTERY_PCT        INTEGER,
    IS_CHARGING           BOOLEAN,
    CONSTRAINT PK_DEVICE_STATUS PRIMARY KEY (ID_DEVICE_STATUS_KEY),
    CONSTRAINT FK_DEVICE_STATUS_ACCOUNT FOREIGN KEY (ID_ACCOUNT_KEY) REFERENCES T_ACCOUNT (ID_ACCOUNT_KEY),
    CONSTRAINT FK_DEVICE_STATUS_DEVICE FOREIGN KEY (ID_DEVICE_KEY) REFERENCES T_DEVICE (ID_DEVICE_KEY),
    CONSTRAINT CK_DEVICE_STATUS_BATTERY CHECK (CT_BATTERY_PCT BETWEEN 0 AND 100)
);
CALL LIB_attach_header('t_device_status');
CREATE UNIQUE INDEX UK_DEVICE_STATUS_DEVICE ON T_DEVICE_STATUS (ID_DEVICE_KEY) WHERE IS_ACTIVE;
